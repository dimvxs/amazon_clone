import type { Metadata } from "next";
import { Inter } from "next/font/google";
import "./globals.css";
import { CartProvider } from "@/contexts/cart.context";
import ClientLayout from "@/components/ClientLayout";
import Image from "next/image";
import promises from "fs/promises";
import path from "path";

const inter = Inter({
  subsets: ["latin"],
  variable: "--font-inter",
});

export const metadata: Metadata = {
  title: "Amazon Clone",
  description: "Generated by create next app",
};

// Функция берет строго ПЕРВУЮ картинку из массива
async function getGlobalBackground() {
  try {
    const filePath = path.join(process.cwd(), "public", "data", "homepage.json");
    const jsonData = await promises.readFile(filePath, "utf-8");
    const data = JSON.parse(jsonData);
    return data.background_image?.[0] || null;
  } catch (error) {
    console.error("Failed to read background image:", error);
    return null;
  }
}

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const backgroundImageSrc = await getGlobalBackground();

  return (
    <html lang="en">
      <body className={`${inter.variable} antialiased min-h-screen flex flex-col relative bg-[#070913]`}>
        
        {/* ГЛОБАЛЬНЫЙ ФОН: Только image[0] для всех разрешений экрана */}
        {backgroundImageSrc && (
          <div className="absolute top-0 left-0 w-full h-[1024px] z-[1] pointer-events-none">
            <div className="absolute inset-0">
              <Image
                src={backgroundImageSrc}
                alt="Global background"
                fill
                sizes="100vw"
                className="object-cover"
                priority
              />
            </div>

            {/* Плавный градиент перетекания картинки в темный фон */}
            <div 
              className="absolute bottom-0 left-0 w-full h-[400px] z-[2]" 
              style={{ 
                background: 'linear-gradient(to bottom, transparent, #070913)' 
              }} 
            />
          </div>
        )}

        {/* Весь остальной интерфейс рендерится поверх фона благодаря z-10 */}
        <div className="relative z-10 flex-1 flex flex-col">
          <CartProvider>
            <ClientLayout>{children}</ClientLayout>
          </CartProvider>
        </div>

      </body>
    </html>
  );
}